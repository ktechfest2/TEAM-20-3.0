// Regenerates supabase/migrations/0008_seed_ng2023_sample.sql from the app registry.
// Usage (repo root): node supabase/admin/generate-0008.mjs
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { loadNg2023 } from "./ng2023-data.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const { source, election, units } = loadNg2023(root);
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

const rows = units.map(
  (u) => `  (${q(u.id)}, ${q(source.id)}, ${q(u.code)}, ${q(u.state)}, ${q(u.lga)}, ${q(u.ward)}, ${q(u.name)}, false)`,
);
const sql = `-- REAL 2023 historical sample (NOT synthetic, NOT INEC-certified). GENERATED by
-- supabase/admin/generate-0008.mjs from src/lib/seed/historical-ng2023.ts; do not edit by hand.
-- Source: ${source.name} — ${source.url} (${source.file}, sha256 ${source.fileSha256}),
-- retrieved ${source.retrievedAt}. Scope: ${source.scope}. Licence: ${source.licenceNote}
-- Adds only the election + polling-unit rows the reference records need (FKs). Reference rows
-- themselves are inserted by supabase/admin/import-ng2023.mjs (idempotent, audited).

insert into elections (id, name, type, date, synthetic) values
  (${q(election.id)}, ${q(election.name)}, ${q(election.type)}, ${q(election.date)}, ${election.synthetic})
on conflict (id) do nothing;

insert into polling_units (id, registry_source, code, state, lga, ward, name, synthetic) values
${rows.join(",\n")}
on conflict (id) do nothing;
`;
const out = path.join(root, "supabase/migrations/0008_seed_ng2023_sample.sql");
writeFileSync(out, sql);
console.log(`wrote ${path.relative(root, out)}: 1 election, ${units.length} polling units`);
